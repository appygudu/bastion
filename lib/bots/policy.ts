import { KNOWN_AGENTS } from "./catalog";

export interface PolicyRule {
  agent: string;
  access: "allow" | "deny";
  training: "allow" | "deny";
  scraping: "allow" | "deny";
}

export function defaultPolicy(): PolicyRule[] {
  return KNOWN_AGENTS.map((agent) => {
    const trainingCrawler = agent.category === "ai-crawler";
    return {
      agent: agent.id,
      access: trainingCrawler ? "deny" : "allow",
      training: trainingCrawler ? "deny" : "allow",
      scraping: trainingCrawler ? "deny" : "allow",
    };
  });
}

export function renderRobots(rules: PolicyRule[]): string {
  const lines = [
    "# Generated by Bastion.",
    "# robots.txt expresses a preference. It does not technically enforce access.",
    "# Content-signal vocabulary is the one documented by Cloudflare:",
    "# https://developers.cloudflare.com/bots/additional-configurations/managed-robots-txt/",
    "",
    "User-agent: *",
    "Content-signal: search=yes, ai-train=no, ai-input=yes",
    "Allow: /",
    "",
  ];
  for (const rule of rules) {
    if (rule.access === "deny" || rule.scraping === "deny") {
      lines.push(`User-agent: ${rule.agent}`, "Disallow: /", "");
    }
  }
  return lines.join("\n").trim() + "\n";
}

export function renderAiTxt(rules: PolicyRule[], host: string): string {
  const lines = [
    "# Generated by Bastion.",
    "# The field names follow draft-car-ai-txt-wellknown-00, an informational Internet-Draft, not a published standard.",
    `# Host: ${host}`,
    "Training: deny",
    "Indexing: allow",
    "Attribution: required",
    "",
    "Agent: *",
    "  Training: deny",
    "  Scraping: allow",
    "",
  ];
  for (const rule of rules) {
    lines.push(`Agent: ${rule.agent}`, `  Training: ${rule.training}`, `  Scraping: ${rule.scraping}`, "");
  }
  return lines.join("\n").trim() + "\n";
}

export function renderMiddleware(rules: PolicyRule[]): string {
  const denied = rules.filter((rule) => rule.access === "deny").map((rule) => rule.agent.toLowerCase());
  return `// Generated by Bastion. Deploy on an application you operate.
// This is an access-control preference for your own process, not an exploit.
const denied = new Set(${JSON.stringify(denied)});

export function bastionPolicy(req, res, next) {
  const ua = String(req.headers["user-agent"] || "").toLowerCase();
  for (const name of denied) {
    if (ua.includes(name)) {
      res.status(403).type("text/plain").send("This crawler is disallowed by the site operator.");
      return;
    }
  }
  next();
}
`;
}
